#!/bin/sh
# pyopsctl install / uninstall — symlinks bin/pyopsctl into the user bin
# dir so `pyopsctl` is on PATH without a venv, without pip, without root.
# The script never touches apt; distribution deps (python3, python3-requests,
# optionally python3-argcomplete for tab completion) are documented as
# prerequisites in ctl/README.md.
set -e

HERE="$(cd "$(dirname "$0")" && pwd -P)"
SRC="$HERE/bin/pyopsctl"
BIN_DIR="${XDG_BIN_HOME:-$HOME/.local/bin}"
TARGET="$BIN_DIR/pyopsctl"

# argcomplete-driven zsh completion installs into the XDG user-share dir.
# zsh's default $fpath has no userspace entry, so install.sh also drops a
# marker-tagged line into ~/.zshrc that extends $fpath. Marker makes the
# uninstall path unambiguous: remove only what install.sh added.
ZSH_COMPLETION_DIR="${XDG_DATA_HOME:-$HOME/.local/share}/zsh/site-functions"
ZSH_COMPLETION_FILE="$ZSH_COMPLETION_DIR/_pyopsctl"
ZSHRC="$HOME/.zshrc"
ZSHRC_FPATH_MARKER="# pyopsctl-install: pyopsctl tab completion"
ZSHRC_FPATH_LINE="fpath=($ZSH_COMPLETION_DIR \$fpath)  $ZSHRC_FPATH_MARKER"

install_zsh_completion() {
    # No-op if argcomplete isn't installed — completion is a nice-to-have,
    # not required for pyopsctl itself to run.
    if ! command -v register-python-argcomplete >/dev/null 2>&1; then
        echo "note: python3-argcomplete not installed; skipping shell completion (apt install python3-argcomplete to enable)" >&2
        return 0
    fi
    mkdir -p "$ZSH_COMPLETION_DIR"
    # `#compdef` first line is the autoload hook zsh's compinit scans
    # for; the rest is argcomplete's generated zsh-driver. compinit
    # autoloads the file on first `pyopsctl<TAB>`, which registers the
    # _python_argcomplete handler — subsequent tabs hit it directly.
    {
        echo "#compdef pyopsctl"
        echo "# auto-generated by pyops/ctl/install.sh — do not edit by hand"
        register-python-argcomplete --shell zsh pyopsctl
    } > "$ZSH_COMPLETION_FILE"
    echo "installed: $ZSH_COMPLETION_FILE"
    if [ -f "$ZSHRC" ] && grep -Fq "$ZSHRC_FPATH_MARKER" "$ZSHRC"; then
        : # already present
    else
        printf "\n%s\n" "$ZSHRC_FPATH_LINE" >> "$ZSHRC"
        echo "appended fpath entry to $ZSHRC (start a new zsh or run \`exec zsh\` to activate)"
    fi
}

uninstall_zsh_completion() {
    if [ -f "$ZSH_COMPLETION_FILE" ]; then
        rm "$ZSH_COMPLETION_FILE"
        echo "uninstalled: removed $ZSH_COMPLETION_FILE"
    fi
    if [ -f "$ZSHRC" ] && grep -Fq "$ZSHRC_FPATH_MARKER" "$ZSHRC"; then
        # Drop only the line tagged with our marker — leaves any other
        # user-managed fpath edits untouched.
        tmp="$(mktemp)"
        grep -Fv "$ZSHRC_FPATH_MARKER" "$ZSHRC" > "$tmp"
        mv "$tmp" "$ZSHRC"
        echo "removed fpath entry from $ZSHRC"
    fi
}

case "${1:-}" in
    --uninstall)
        if [ -L "$TARGET" ]; then
            rm "$TARGET"
            echo "uninstalled: removed $TARGET"
        elif [ -e "$TARGET" ]; then
            echo "refusing to remove $TARGET: not a symlink" >&2
            exit 1
        else
            echo "no symlink at $TARGET — nothing to uninstall"
        fi
        uninstall_zsh_completion
        ;;
    "")
        if [ ! -x "$SRC" ]; then
            echo "launcher not found or not executable: $SRC" >&2
            exit 1
        fi
        mkdir -p "$BIN_DIR"
        ln -sfn "$SRC" "$TARGET"
        echo "installed: $TARGET -> $SRC"
        case ":$PATH:" in
            *":$BIN_DIR:"*) ;;
            *) echo "warning: $BIN_DIR is not on PATH — add it (e.g. in ~/.profile) to use pyopsctl from anywhere" >&2 ;;
        esac
        install_zsh_completion
        ;;
    -h|--help)
        cat <<EOF
usage: install.sh             # symlink bin/pyopsctl into \$XDG_BIN_HOME (or ~/.local/bin)
       install.sh --uninstall # remove the symlink + completion

Prerequisites: python3 (>= 3.11 for stdlib tomllib), python3-requests.
Optional:      python3-argcomplete (zsh tab completion via fpath wiring).
EOF
        ;;
    *)
        echo "usage: $0 [--uninstall|--help]" >&2
        exit 2
        ;;
esac
