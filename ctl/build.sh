#!/bin/bash
# Build a Debian binary package for pyopsctl using nothing beyond
# `dpkg-deb` (no fpm/Ruby, no debhelper/dh-python). The package is
# `Architecture: all` because pyopsctl is pure-Python stdlib + requests.
#
# Layout produced:
#   /usr/bin/pyopsctl                                         (launcher)
#   /usr/lib/python3/dist-packages/pyopsctl/                  (package source)
#   /usr/lib/python3/dist-packages/pyopsctl/_version.py       (baked at build)
#   /usr/share/zsh/vendor-completions/_pyopsctl               (zsh autoload)
#   /usr/share/bash-completion/completions/pyopsctl           (bash hook)
#   /usr/share/doc/pyopsctl/README.md
#   /usr/share/doc/pyopsctl/copyright
#
# Targets Ubuntu 24.04 (noble) and Debian 13 (trixie) as the floor.
# Both ship python3 ≥ 3.12, python3-requests, and python3-argcomplete
# in main, so Depends/Recommends resolve without extra repos.
#
# Run from anywhere; invokes itself relative to its own location.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." >/dev/null 2>&1 && pwd)"
VERSION_FILE="$PROJECT_ROOT/VERSION"
if [[ ! -f "$VERSION_FILE" ]]; then
    echo "VERSION file not found at $VERSION_FILE" >&2
    exit 1
fi
VERSION="$(tr -d '[:space:]' < "$VERSION_FILE")"
if [[ -z "$VERSION" ]]; then
    echo "VERSION file is empty" >&2
    exit 1
fi

ARCH=all
PKGNAME=pyopsctl
DIST_DIR="$SCRIPT_DIR/dist"
STAGE="$DIST_DIR/${PKGNAME}_${VERSION}_${ARCH}"
DEB="$DIST_DIR/${PKGNAME}_${VERSION}_${ARCH}.deb"

rm -rf "$STAGE" "$DEB"
mkdir -p "$STAGE/DEBIAN" \
         "$STAGE/usr/bin" \
         "$STAGE/usr/lib/python3/dist-packages" \
         "$STAGE/usr/share/zsh/vendor-completions" \
         "$STAGE/usr/share/bash-completion/completions" \
         "$STAGE/usr/share/doc/$PKGNAME"

# Package source. Exclude __pycache__ — let dpkg's triggers (py3compile
# at install time) rebuild .pyc files for the target Python version.
cp -r "$SCRIPT_DIR/pyopsctl" "$STAGE/usr/lib/python3/dist-packages/"
find "$STAGE/usr/lib/python3/dist-packages/pyopsctl" -type d -name __pycache__ -exec rm -rf {} +
find "$STAGE/usr/lib/python3/dist-packages/pyopsctl" -type f -name "*.pyc" -delete

# Version baked next to __init__.py so the package-installed CLI
# doesn't depend on a VERSION file the deb doesn't ship.
cat > "$STAGE/usr/lib/python3/dist-packages/pyopsctl/_version.py" <<EOF
# auto-generated by ctl/build.sh — do not edit by hand
__version__ = "$VERSION"
EOF

# Launcher. dist-packages is already on Python's import path on
# Debian/Ubuntu so no sys.path mangling is needed (unlike the
# install.sh symlink launcher which has to bootstrap from the repo).
cat > "$STAGE/usr/bin/pyopsctl" <<'EOF'
#!/usr/bin/env python3
# PYTHON_ARGCOMPLETE_OK
"""pyopsctl launcher (Debian package variant).

Shipped by the pyopsctl .deb at /usr/bin/pyopsctl. The pyopsctl
package itself is installed under /usr/lib/python3/dist-packages —
already on Python's default import path — so this stays minimal.
"""
import sys
from pyopsctl.__main__ import main

if __name__ == "__main__":
    sys.exit(main())
EOF
chmod 755 "$STAGE/usr/bin/pyopsctl"

# Completion files. Generated by argcomplete now (build host needs
# python3-argcomplete + python3-requests so the temporary import of
# pyopsctl during `register-python-argcomplete pyopsctl` works).
# The build PYTHONPATH points at the staged pyopsctl, not the dev
# checkout, so the embedded _version.py is the one that runs.
PYTHONPATH="$STAGE/usr/lib/python3/dist-packages:${PYTHONPATH:-}" \
    PATH="$STAGE/usr/bin:$PATH" \
    register-python-argcomplete --shell zsh pyopsctl \
    | { echo "#compdef pyopsctl"; echo "# generated by ctl/build.sh — do not edit"; cat; } \
    > "$STAGE/usr/share/zsh/vendor-completions/_pyopsctl"
PYTHONPATH="$STAGE/usr/lib/python3/dist-packages:${PYTHONPATH:-}" \
    PATH="$STAGE/usr/bin:$PATH" \
    register-python-argcomplete --shell bash pyopsctl \
    > "$STAGE/usr/share/bash-completion/completions/pyopsctl"

# Docs.
cp "$SCRIPT_DIR/README.md" "$STAGE/usr/share/doc/$PKGNAME/README.md"
cat > "$STAGE/usr/share/doc/$PKGNAME/copyright" <<'EOF'
Format: https://www.debian.org/doc/packaging-manuals/copyright-format/1.0/
Upstream-Name: pyopsctl
Upstream-Contact: Ralph Alexander Bariz <ralph.bariz@pm.me>
Source: https://git.ralph.or.at/pyops/pyops

Files: *
Copyright: 2026 Ralph Alexander Bariz
License: proprietary
 Distributed as part of the pyops project. See repository for terms.
EOF

# Control file. Depends pinned to Ubuntu 24.04 floors:
#   python3 (>= 3.12)        — Ubuntu 24.04 default, stdlib tomllib
#   python3-requests         — http client
# Recommends:
#   python3-argcomplete      — shell tab completion. CLI runs fine
#                              without it (the autocomplete call is
#                              guarded by try/except ImportError).
control_file="$STAGE/DEBIAN/control"
cat > "$control_file" <<EOF
Package: $PKGNAME
Version: $VERSION
Section: admin
Priority: optional
Architecture: $ARCH
Depends: python3 (>= 3.12), python3-requests
Recommends: python3-argcomplete
Maintainer: Ralph Alexander Bariz <ralph.bariz@pm.me>
Homepage: https://git.ralph.or.at/pyops/pyops
Description: Remote-admin CLI for the pyops execution platform
 pyopsctl talks the pyops HTTP API: scriptlet, job, debug, health,
 metrics, and config command groups. Designed to be driven by both
 a human operator at a terminal and by agents (LLM-driven or
 otherwise) and shell scripts — non-interactive, no per-call password
 prompts, no venv, no pip.
 .
 Per-profile credentials live at ~/.config/pyops/config.toml (mode
 0600). When the profile carries an api_key, requests use
 HTTP Basic Auth; without an api_key, X-User is sent directly.
EOF

# Build.
dpkg-deb --build --root-owner-group "$STAGE" "$DEB" >/dev/null
echo "built: $DEB"
dpkg-deb --info "$DEB" | sed -n '/Package:/,/Description:/p'
